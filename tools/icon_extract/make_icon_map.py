"""Writes ps4_plugin/source/icon_map.h from an icon pack's index.txt (make_icon_pack.py).

The table only holds figure ids, variant values and the games' own icon names - no art. With
it the plugin finds each figure's icon in whichever game is running (on-console extraction).

  python tools/icon_extract/make_icon_map.py <icon pack folder>/index.txt ps4_plugin/source/icon_map.h

extra_icon_map.txt (next to this script) adds entries the Imaginators table lacks (trophies etc.).
"""
import os
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    rows = []
    extra = os.path.join(os.path.dirname(os.path.abspath(__file__)), "extra_icon_map.txt")
    for path in (src, extra):
        for line in open(path, encoding="utf-8"):
            p = line.split()
            if len(p) == 3 and p[0] not in ("size", "source") and not p[0].startswith("#"):
                row = (int(p[0]), int(p[1]), p[2])
                if row not in rows:
                    rows.append(row)
    names = sorted({r[2] for r in rows})
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/icon_extract/make_icon_map.py - do not edit.\n")
        f.write("// Figure id + variant value (-1 = any) -> name of the game's collection icon.\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write("static const char *const k_icon_names[%d] = {\n" % len(names))
        for n in names:
            f.write('    "%s",\n' % n)
        f.write("};\n\n")
        f.write("static const struct { uint16_t id; int16_t variant; uint16_t name; } k_icon_map[%d] = {\n" % len(rows))
        for fid, var, n in rows:
            f.write("    { %d, %d, %d },\n" % (fid, var, names.index(n)))
        f.write("};\n")
    print(len(rows), "entries,", len(names), "icon names")


if __name__ == "__main__":
    main()
