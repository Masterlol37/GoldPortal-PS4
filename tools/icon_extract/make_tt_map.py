"""Trap Team (CUSA00697): figure id + variant -> streamed icon texture, as a C table.

Trap Team keeps its collection pictures in misc/ui_collection_*.arc (IGA v11, files named only by a
32-bit hash, stored uncompressed: IGZ v8 with a 192x192 BC3 igImage2, 256-byte prefix). The names
are in the matching .bld (IGA v11, LZMA blocks): its sprite-level IGZ lists every picture as
".../<id>_<variant>_<Name>.png" in its string table, and its script records hold the texture hashes
in the same order (each record also contains the figure id, which is used to stay in step).

The resulting table has only numbers (id, variant, hash) and is compiled into the plugin, which then
reads the pictures from the user's own game.

  python tools/icon_extract/make_tt_map.py <misc folder> ps4_plugin/source/tt_icons.h
"""
import os
import re
import struct
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from iga import IgaArchive  # noqa: E402
from igz import Igz  # noqa: E402


def mapping(bld_path, arc_path):
    bld, arc = IgaArchive(bld_path), IgaArchive(arc_path)
    hashes = {int(n, 16) for n in arc.names}
    best = None
    for i in range(len(bld.names)):
        z = Igz(bld.read(i))
        # Every collection picture in string-table order (also backgrounds etc.: they have
        # streamed textures too and keep the order in step).
        pngs = [s for s in z.strings if "/collection_images/" in s.lower() and s.lower().endswith(".png")]
        if pngs and (best is None or len(pngs) > len(best[1])):
            best = (z, pngs)
    z, pngs = best
    pool = z.pools[0]
    u = lambda o: struct.unpack_from("<I", pool, o)[0]
    hpos = [o for o in range(0, len(pool) - 3, 4) if u(o) in hashes]
    if len(hpos) != len(pngs):
        print("  WARNING: %d hashes but %d picture names - order may not line up" % (len(hpos), len(pngs)))
    out = []
    for o, s in zip(hpos, pngs):
        m = re.match(r".*/(\d+)_(\d+)(?:_[^/]*)?\.png$", s, re.I)   # traps: "<id>_<variant>.png"
        if m:
            out.append((int(m.group(1)), int(m.group(2)), u(o), s.split("/")[-1]))
    print(os.path.basename(arc_path), ":", len(out), "figure pictures of", len(hpos), "hashes,", len(pngs), "names")
    return out


def main():
    misc, dst = sys.argv[1], sys.argv[2]
    rows = []
    for arc_i, base in enumerate(("ui_collection_champions", "ui_collection_traps")):
        for fid, var, h, name in mapping(os.path.join(misc, base + ".bld"), os.path.join(misc, base + ".arc")):
            rows.append((fid, var, h, arc_i, name))
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/icon_extract/make_tt_map.py - do not edit.\n")
        f.write("// Trap Team: figure id + variant -> hash name of its picture in misc/<archive>.arc\n")
        f.write("#pragma once\n#include <stdint.h>\n\n")
        f.write('static const char *const k_tt_archives[2] = { "ui_collection_champions.arc", "ui_collection_traps.arc" };\n')
        f.write("static const struct { uint16_t id, variant; uint32_t hash; uint8_t archive; } k_tt_icons[%d] = {\n" % len(rows))
        for fid, var, h, a, name in rows:
            f.write("    { %d, %d, 0x%08X, %d },   // %s\n" % (fid, var, h, a, name))
        f.write("};\n")
    print(len(rows), "rows written")


if __name__ == "__main__":
    main()
