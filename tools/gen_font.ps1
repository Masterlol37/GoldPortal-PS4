# Renders a proportional 8-bit alpha bitmap font (Latin-1, 32..255) into ps4_plugin/source/font_data.h.
#
# The shipped font_data.h is rendered from Noto Sans SemiBold (SIL Open Font License 1.1, see
# ps4_plugin/source/FONT_LICENSE.txt). Get the font from the Noto project:
#   https://github.com/notofonts/notofonts.github.io/raw/main/fonts/NotoSans/hinted/ttf/NotoSans-SemiBold.ttf
#
# Usage (Windows PowerShell):
#   powershell -File tools/gen_font.ps1 -FontFile <path>\NotoSans-SemiBold.ttf [-Size 20]
# Only use fonts whose license allows redistributing rendered glyphs (e.g. OFL fonts).
param([Parameter(Mandatory = $true)][string]$FontFile, [int]$Size = 20)
Add-Type -AssemblyName System.Drawing

$out = Join-Path $PSScriptRoot "..\ps4_plugin\source\font_data.h"
$pfc = New-Object System.Drawing.Text.PrivateFontCollection
$pfc.AddFontFile((Resolve-Path $FontFile).Path)
$family = $pfc.Families[0]
$f = New-Object System.Drawing.Font($family, $Size, [System.Drawing.FontStyle]::Regular, [System.Drawing.GraphicsUnit]::Pixel)
$H = [int][Math]::Ceiling($f.GetHeight()) + 2
$probe = New-Object System.Drawing.Bitmap(1, 1)
$gp = [System.Drawing.Graphics]::FromImage($probe)
$fmt = [System.Drawing.StringFormat]::GenericTypographic
$fmt.FormatFlags = $fmt.FormatFlags -bor [System.Drawing.StringFormatFlags]::MeasureTrailingSpaces

$widths = @(); $offsets = @(); $bytes = New-Object System.Collections.Generic.List[byte]
for ($c = 32; $c -le 255; $c++) {
    $ch = [string][char]$c
    if ($c -ge 127 -and $c -le 160) { $ch = " " }
    $w = [int][Math]::Ceiling($gp.MeasureString($ch, $f, 1000, $fmt).Width)
    if ($w -lt 1) { $w = [int]($Size / 3) }
    $bmp = New-Object System.Drawing.Bitmap(($w + 4), $H)
    $g = [System.Drawing.Graphics]::FromImage($bmp)
    $g.Clear([System.Drawing.Color]::Black)
    $g.TextRenderingHint = [System.Drawing.Text.TextRenderingHint]::AntiAliasGridFit
    $g.DrawString($ch, $f, [System.Drawing.Brushes]::White, 0, 1, $fmt)
    $g.Dispose()
    $widths += ($w + 1)
    $offsets += $bytes.Count
    for ($y = 0; $y -lt $H; $y++) { for ($x = 0; $x -le $w; $x++) { $bytes.Add($bmp.GetPixel($x, $y).G) } }
    $bmp.Dispose()
}

$name = $family.Name
$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("// Generated by tools/gen_font.ps1 from $name, ${Size}px. Do not edit.")
[void]$sb.AppendLine("// Font: SIL Open Font License 1.1 - see FONT_LICENSE.txt next to this file.")
[void]$sb.AppendLine("#pragma once")
[void]$sb.AppendLine("#include <stdint.h>")
[void]$sb.AppendLine("#define FONT_HEIGHT $H")
[void]$sb.AppendLine("#define FONT_FIRST 32")
[void]$sb.AppendLine("#define FONT_LAST 255")
[void]$sb.AppendLine("static const uint8_t font_width[224] = {" + ($widths -join ",") + "};")
[void]$sb.AppendLine("static const uint32_t font_offset[224] = {" + ($offsets -join ",") + "};")
[void]$sb.Append("static const uint8_t font_alpha[" + $bytes.Count + "] = {")
for ($i = 0; $i -lt $bytes.Count; $i++) {
    if ($i % 40 -eq 0) { [void]$sb.Append("`n") }
    [void]$sb.Append($bytes[$i]); [void]$sb.Append(",")
}
[void]$sb.AppendLine("`n};")
[IO.File]::WriteAllText($out, $sb.ToString())
"wrote $out ($name, height $H, $($bytes.Count) bytes)"
